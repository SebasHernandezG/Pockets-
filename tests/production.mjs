import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ acceptDownloads: true });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto(process.env.POCKETS_TEST_URL || 'http://127.0.0.1:4173/');
await page.locator('[name="income"]').fill('1000.50');
await page.locator('[name="source"]').fill('Beca');
await page.getByRole('button', { name: 'Crear mi primer registro' }).click();
await page.getByRole('button', { name: 'Agregar gasto de Comida', exact: true }).click();
await page.locator('[name="amount"]').fill('1200.75');
await page.getByRole('button', { name: 'Guardar gasto', exact: true }).click();
assert.match(await page.locator('.negative strong').textContent(), /200,25/);
const downloaded = page.waitForEvent('download');
await page.getByRole('button', { name: 'Descargar PDF', exact: true }).click();
const pdf = await downloaded;
await pdf.saveAs('qa/production.pdf');
assert.equal((await readFile('qa/production.pdf')).subarray(0, 5).toString(), '%PDF-');
assert.deepEqual(errors, []);
await browser.close();
console.log('PASS: built production app, negative balance, lazy-loaded PDF download, no browser errors.');
